const step = (
  name: string,
  informText?: string,
  requiresEmailAddress = false,
  requiresCompany = false,
): DocStepResponse => ({
  id: _stepId--,
  code: '',
  name,
  informText,
  requiresEmailAddress,
  requiresCompany,
  requiresDocuments: false,
  sortOrder: 0,
});

